def get(name: str) -> Launchable | None:
    return LAUNCHABLE.get(name)


def names() -> list[str]:
    return sorted(LAUNCHABLE)


def suggest(name: str, limit: int = 3) -> list[str]:
    """Nearest names, for the "misspelled tap target" diagnostic."""
    import difflib

    return difflib.get_close_matches(name, LAUNCHABLE, n=limit, cutoff=0.5)
