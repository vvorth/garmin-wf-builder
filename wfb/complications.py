"""Complication types a watch face can *launch* (ADR 0006 §6).

Tapping an element on a watch face cannot open an arbitrary app: the platform
offers exactly one door, ``Complications.exitTo(id)``, documented as "launches
the app associated with the complication" (``Toybox/Complications.html``, API
level 4.2.0).  So an interactive element names a **complication type**, and the
watch opens whatever glance or app owns that type -- Body Battery opens
Garmin's Body Battery glance, and so on.

This is a different question from :mod:`wfb.catalog`'s ``complication_*``
readers, which is why it is a different table.  There, a complication is a
value to *read*, and only nine are worth reading because everything else is
already reachable more cheaply through ``ActivityMonitor``/``Activity``/
``Weather``/``UserProfile``.  Here every type is a valid destination whether or
not the design displays its value, so all 42 are listed.

Generated by reading the ``COMPLICATION_TYPE_*`` table in
``$CIQ_SDK/doc/Toybox/Complications.html`` rather than typed from memory --
the same discipline :mod:`wfb.catalog` follows, and for the same reason: a
name is a claim about a symbol that exists, and it should be checked.

``since`` is the API level that *type* was added, which is not the same as the
device supporting it -- a device's own ConnectIQ ceiling can sit below it (see
``activity.sleep_score`` in :mod:`wfb.catalog` for a concrete case).  A tap on
a type the watch does not know simply does nothing; it is not a crash.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Launchable:
    """One ``COMPLICATION_TYPE_*`` an ``on_hold:`` may name."""

    #: The spelling used in a design file: the constant, lowercased.
    name: str
    #: The Monkey C constant, emitted as ``Complications.<constant>``.
    constant: str
    #: The API level this type was introduced at.
    since: str


def _l(name: str, constant: str, since: str) -> Launchable:
    return Launchable(name, constant, since)


