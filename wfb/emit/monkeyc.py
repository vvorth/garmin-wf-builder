"""Monkey C generation.

ADR 0003 sets the bar: the generated code is reviewed, debugged and extended by
a human, so it must read as though someone wrote it.  Concretely --

* symbol names are derived from element ids, so they are stable across builds;
* a header cites the source file and the generator version;
* every drawing block carries a comment naming the YAML element it came from;
* layout constants are named in a per-device ``Layout`` module rather than
  inlined as bare numbers;
* every nullable read is guarded, and the guard states the ``when_absent``
  policy that produced it.

The code targets ``-l 3`` (strict typecheck) cleanly.  A generator has no excuse
for emitting code that fails strict checking.
"""

from __future__ import annotations

from dataclasses import dataclass

from .. import __version__, catalog, formatting, icons
from ..catalog import READERS, Tier, Type
from ..ir import Expression, Face, IconElement, Progress, Shape, Text, font_resource_id
from ..layout import (
    PlacedIcon, PlacedProgress, PlacedShape, PlacedText, ResolvedFace,
)
from ..units import IntBox
from .writer import Writer

#: Base Toybox imports every generated face needs.
_BASE_IMPORTS = ("Toybox.Graphics", "Toybox.Lang", "Toybox.WatchUi")


@dataclass
class SourceFile:
    """One generated file, and where it belongs in the project."""

    #: Relative to the build directory, e.g. ``source/SliceView.mc``.
    path: str
    text: str


def source_label(path) -> str:
    """The design's path as it should appear in a generated header.

    Relative to the working directory when it is under it, and the bare filename
    otherwise.  An absolute path would make generated output differ between
    machines, which would defeat the golden-file tests and make every diff noisy.
    """
    import os
    from pathlib import Path

    try:
        relative = os.path.relpath(Path(path).resolve(), Path.cwd())
    except (OSError, ValueError):
        return Path(path).name
    return Path(path).name if relative.startswith("..") else relative


def header(face: Face, extra: str = "") -> str:
    lines = [
        f"Generated by garmin-wf-builder {__version__} -- do not edit.",
        f"Source:    {source_label(face.source_path)}",
        f"Face:      {face.name} (format {face.format})",
    ]
    if extra:
        lines.append(extra)
    lines.append("Regenerate with `wfb build`.  Edits here are lost on the next build;")
    lines.append("hand-written Monkey C belongs in a `raw` element instead (ADR 0007).")
    return "\n".join(lines)


