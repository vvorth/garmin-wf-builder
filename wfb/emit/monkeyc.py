def _emit_complication_slot_icon_method(w: Writer, resolved: ResolvedFace,
                                        placed: PlacedComplicationSlot) -> None:
    """`iconFor<Id>(t)` -- one slot's `Complications.Type` -> catalogue name
    (via `IconGlyphs.glyph`) -> drawn glyph lookup.

    A generated method rather than an inline mutable local: Monkey C locals
    cannot be given an explicit `as String?` type ("Invalid explicit typing
    of a local variable", from a real build), so there is no way to declare
    one that starts `null` and is later assigned a `String`.  Returning
    through a function whose own signature declares `String?` sidesteps that
    -- the call site's local infers its type from the call expression
    instead.  Verified buildable under `-l 3`
    (docs/research/probes/config-axes/ProbeView.mc's `iconFor`).
    """
    element = placed.element
    face = resolved.face
    slot = face.config_data[element.slot]
    mapped = {name: icons.COMPLICATION_ICON[name] for name in slot.choices
             if name in icons.COMPLICATION_ICON}
    w.blank()
    w.doc(f"`{element.id}`'s icon, chosen from the wearer's picked type alone -- not\n"
          "from the pulled value, so it still shows even on a frame the reading itself\n"
          "could not be pulled.")
    method = complication_slot_icon_method(element.id)
    with w.block(f"private function {method}(t as Complications.Type) as String?"):
        with w.block("switch (t)"):
            for name in slot.choices:
                icon_name = mapped.get(name)
                if icon_name is None:
                    continue
                ctype = complications.TYPES[name]
                w.line(f'case Complications.{ctype.constant}: return "{icon_name}";')
            w.line("default: return null;")
    w.blank()
    # `IconGlyphs.glyph` turns the catalogue name into the actual character --
    # see `emit_icon_glyphs`'s own docstring for why a name, not a raw
    # character, is what this method should have produced in the first
    # place, matching the weather-icon split.


def _emit_complication_slot(w: Writer, resolved: ResolvedFace, placed: PlacedComplicationSlot) -> None:
    """A native Data-axis slot: pull the wearer's chosen complication, choose
    an icon from its *type* alone, then draw the two as one centred pair.

    Everything here is a plain per-frame pull (`WfbComplications.valueOf`),
    exactly like an ordinary `complication.<name>` catalogue source -- the
    compiled field just holds a `Complications.Id` the *wearer* can repoint,
    instead of a build-time-fixed one (CLAUDE.md: "complications are pulled
    not cached", docs/research/probes/complication-pull/).

    The icon is chosen from `chosenId.getType()`, not from the pulled value,
    so it still shows even on a frame the reading itself could not be pulled
    -- verified buildable under `-l 3`
    (docs/research/probes/config-axes/ProbeView.mc's `iconFor`).  The icon
    and the reading are centred on this element's own anchor as one pair, via
    `Dc.getTextWidthInPixels` -- the actual text is not known until the value
    is pulled, so unlike every other element this cannot be precomputed at
    build time (ADR 0004's one deliberate exception, and for exactly that
    reason).

    Every `complication_slot` -- not only ones with `on_hold:` -- starts with
    a `_pulsing` guard: the native editor can animate *any* slot's highlight
    (`getComplicationDrawable`), and the SDK sample's own comment on this
    exact hazard is what makes skipping the normal draw mandatory while that
    happens -- "This prevents the complication from being drawn on the watch
    face while it is pulsing."  A design with `complication_slot` elements
    always has at least one, so this function running at all is exactly the
    condition under which the guard applies -- see `_emit_pulsing_field`.
    """
    element = placed.element
    prefix = _const_prefix(placed.id)
    face = resolved.face
    slot = face.config_data[element.slot]
    field = config_field(f"data_{element.slot}")
    unique = config_data_ids(face)[element.slot]

    w.comment("the editor is animating this exact slot right now -- skip it, or the")
    w.comment("system draws it twice while it pulses (SDK sample's own comment)")
    with w.block(f"if (_pulsing == {unique})"):
        w.line("return;")
    w.blank()
    w.comment(f"slot: config.data.{element.slot}")
    w.line(f"var chosenId = {field};")

    icon_font_expr = None
    if placed.icon_font_key is not None:
        w.line(f"var iconFont = _{_field(placed.icon_font_key)};")
        w.comment("the icon is chosen from the wearer's picked *type*, so it still shows")
        w.comment("even on a frame the reading itself could not be pulled -- a name")
        w.comment("(WfbComplications-style split), then IconGlyphs.glyph turns it into")
        w.comment("the actual character, exactly like a dynamic weather icon does")
        w.line(f"var iconName = {complication_slot_icon_method(element.id)}(chosenId.getType());")
        w.line("var iconGlyph = (iconName != null) ? IconGlyphs.glyph(iconName) : null;")
        w.blank()
        icon_font_expr = "iconFont"

    if placed.font_is_custom:
        w.line(f"var textFont = _{_field(placed.font_reference)};")
        with w.block("if (textFont == null)"):
            w.line("return;  // the font resource failed to load")
        font_expr = "textFont"
    else:
        font_expr = f"Graphics.{placed.font_reference}"
    w.blank()

    def _emit_absent() -> None:
        if element.when_absent == "placeholder":
            w.comment("when_absent: placeholder")
            w.line(f'text = "{element.placeholder}";')
        else:
            w.comment("when_absent: hide -- the reading blanks, the icon (if any) stays")

    w.line('var text = "";')
    w.line("var pulled = WfbComplications.valueOf(chosenId);")
    with w.block("if (pulled == null)"):
        _emit_absent()
    with w.block("else"):
        # `pulled.value` is read into its own local, and narrowed through
        # *that* local rather than re-read off `pulled` -- monkeyc cannot
        # narrow a null check across a repeated field-access expression
        # (CLAUDE.md), only across a local variable, and `pulled` itself
        # stays narrowed for the whole of this `else` (it never leaves that
        # local's own guarded scope), which is what still lets `pulled.
        # shortLabel`/`.longLabel`/`.unit` below be read unconditionally.
        w.line("var value = pulled.value;")
        with w.block("if (value == null)"):
            _emit_absent()
        with w.block("else"):
            if element.label in ("short", "long"):
                attr = "shortLabel" if element.label == "short" else "longLabel"
                w.line(f"var label = pulled.{attr};")
                with w.block("if (label != null)"):
                    w.line('text = label + " ";')
            w.line("text += value.toString();")
            if element.unit:
                w.line("text += WfbComplications.unitSuffix(pulled.unit);")
    w.blank()

    w.line(f"dc.setColor({_color(element.color)}, Graphics.COLOR_TRANSPARENT);")
    w.line(f"var textWidth = dc.getTextWidthInPixels(text, {font_expr});")
    w.line("var iconWidth = 0;")
    if icon_font_expr is not None:
        with w.block(f"if (iconGlyph != null && {icon_font_expr} != null)"):
            w.line(
                f"iconWidth = dc.getTextWidthInPixels(iconGlyph, {icon_font_expr}) + "
                f"{COMPLICATION_SLOT_ICON_GAP};"
            )
    w.line("var totalWidth = iconWidth + textWidth;")
    w.line(f"var startX = Layout.{prefix}_CX - totalWidth / 2;")
    if icon_font_expr is not None:
        with w.block(f"if (iconGlyph != null && {icon_font_expr} != null)"):
            w.line(f"dc.drawText(startX, Layout.{prefix}_CY, {icon_font_expr}, iconGlyph,")
            w.line("            Graphics.TEXT_JUSTIFY_LEFT | Graphics.TEXT_JUSTIFY_VCENTER);")
    w.line(f"dc.drawText(startX + iconWidth, Layout.{prefix}_CY, {font_expr}, text,")
    w.line("            Graphics.TEXT_JUSTIFY_LEFT | Graphics.TEXT_JUSTIFY_VCENTER);")


def _emit_graph_fields(w: Writer, graphs: list) -> None:
    """One cached series (plus its auto bounds, where asked for) per `graph`.

    Rebuilt once a minute (`_emit_graph`'s cadence check), not per frame --
    see `runtime-lib/WfbSeries.mc`'s module docstring for why this is not the
    TTL cache this project deleted.
    """
    if not graphs:
        return
    for placed in graphs:
        element = placed.element
        w.doc(f"`{element.id}`: the cached {element.series!r} series.")
        w.line(f"private var {graph_series_field(element.id)} as Array<Float?> = "
               "[] as Array<Float?>;")
        # heart_rate's auto bound comes from the iterator's own getMin/getMax,
        # which is a Number; every other series' comes from WfbSeries.autoMin/
        # autoMax over the collected Array<Float?>, which is a Float.
        auto_type = ("Number" if element.series_def is not None
                     and element.series_def.acquisition is Acquisition.HEART_RATE
                     else "Float")
        zero = "0" if auto_type == "Number" else "0.0"
        if element.min_auto:
            w.line(f"private var {graph_min_field(element.id)} as {auto_type} = {zero};")
        if element.max_auto:
            w.line(f"private var {graph_max_field(element.id)} as {auto_type} = {zero};")
        w.doc(f"`{element.id}`: the minute this series was last rebuilt.")
        w.line(f"private var {graph_built_field(element.id)} as Number = -1;")
    w.blank()


def _emit_graph(w: Writer, placed: PlacedGraph) -> None:
    """The rebuild-cadence check, then one drawing call per `style:`.

    The check runs here rather than unconditionally in `onUpdate` -- after
    the element's own guards, alongside every other kind's actual drawing --
    so a hidden graph does not pay for a rebuild nobody will see this frame.
    """
    element = placed.element
    prefix = _const_prefix(placed.id)
    built = graph_built_field(element.id)
    w.comment("the sample interval here is minutes, so rebuilding more often than")
    w.comment("once a minute could not show anything new (WfbSeries.mc's docstring)")
    w.line("var graphMinute = System.getClockTime().min;")
    with w.block(f"if (graphMinute != {built})"):
        w.line(f"{built} = graphMinute;")
        w.line(f"{graph_rebuild_method(element.id)}();")
    w.blank()

    values = graph_series_field(element.id)
    lo = (f"{graph_min_field(element.id)}.toFloat()" if element.min_auto
          else f"({element.min.code}).toFloat()")
    hi = (f"{graph_max_field(element.id)}.toFloat()" if element.max_auto
          else f"({element.max.code}).toFloat()")
    w.line(f"dc.setColor({_color(element.color)}, Graphics.COLOR_TRANSPARENT);")
    if element.style == "line":
        w.line(f"WfbSeries.drawLine(dc, Layout.{prefix}_X, Layout.{prefix}_Y, "
               f"Layout.{prefix}_WIDTH, Layout.{prefix}_HEIGHT,")
        w.line(f"                   Layout.{prefix}_THICKNESS, {values}, {lo}, {hi});")
    elif element.style == "area":
        w.line(f"WfbSeries.drawArea(dc, Layout.{prefix}_X, Layout.{prefix}_Y, "
               f"Layout.{prefix}_WIDTH, Layout.{prefix}_HEIGHT,")
        w.line(f"                   {values}, {lo}, {hi});")
    else:  # bars
        w.line(f"WfbSeries.drawBars(dc, Layout.{prefix}_X, Layout.{prefix}_Y, "
               f"Layout.{prefix}_WIDTH, Layout.{prefix}_HEIGHT,")
        w.line(f"                   Layout.{prefix}_BAR_WIDTH, {values}, {lo}, {hi});")


def _emit_graph_rebuild(w: Writer, placed: PlacedGraph) -> None:
    """`rebuild<Id>()` -- recompute one graph's cached series.

    `heart_rate` is the one hand-written shape in `WfbSeries.mc`, shared by
    every design that plots it; every other series loops over its own array
    here, generated per project, because the field a design binds
    (`day.steps` vs. `day.calories`, `hour.temperature` vs. `hour.uvIndex`)
    varies and Monkey C offers no way to pass one.
    """
    element = placed.element
    src = element.series_def
    w.blank()
    w.doc(f"Recompute `{element.id}`'s {element.series!r} series.")
    with w.block(f"private function {graph_rebuild_method(element.id)}() as Void"):
        if src.acquisition is Acquisition.HEART_RATE:
            _emit_hr_rebuild(w, element)
        else:
            _emit_array_rebuild(w, element, src)


def _emit_hr_rebuild(w: Writer, element: Graph) -> None:
    """`heart_rate`: acquire the iterator, take its free min/max, then hand
    it to `WfbSeries` to bin (a duration range) or collect (a count range).

    `getMin()`/`getMax()` must run before the iterator is consumed by
    `next()` -- both queries are metadata on the iterator, not a cursor
    advance, confirmed against the reference probe
    (`docs/research/probes/graph-series/`), which calls them in exactly this
    order for exactly this reason.
    """
    period = (f"new Time.Duration({element.range_value})" if element.range_kind == "duration"
              else str(element.range_value))
    w.line(f"var iterator = ActivityMonitor.getHeartRateHistory({period}, false);")
    if element.min_auto:
        w.line("var lo = iterator.getMin();")
        w.line(f"{graph_min_field(element.id)} = (lo != null) ? lo : 0;")
    if element.max_auto:
        w.line("var hi = iterator.getMax();")
        w.line(f"{graph_max_field(element.id)} = (hi != null) ? hi : 0;")
    if element.range_kind == "duration":
        w.line(f"{graph_series_field(element.id)} = WfbSeries.binHeartRate("
               f"iterator, {element.sample_count}, {element.range_value});")
    else:
        w.line(f"{graph_series_field(element.id)} = WfbSeries.collectHeartRate(iterator);")


def _emit_array_rebuild(w: Writer, element: Graph, src) -> None:
    """`steps`/`calories`/.../`daily_precipitation_chance`: one short array,
    read into a fixed-size `Array<Float?>` -- `null` past the end when the
    acquired array is shorter than the requested sample count, which is the
    ordinary case for a design new enough not to have 7 days of history yet.
    """
    info = series.ACQUISITION[src.acquisition]
    n = element.sample_count
    values = graph_series_field(element.id)
    w.line(f"var raw = {info.call};")
    w.line(f"var out = new [{n}] as Array<Float?>;")
    with w.block(f"for (var i = 0; i < {n}; i += 1)"):
        w.line("out[i] = null;")

    def fill() -> None:
        w.line(f"var count = WfbSeries.min({n}, raw.size());")
        with w.block("for (var i = 0; i < count; i += 1)"):
            if info.newest_first:
                w.comment("most recent first on the wire; oldest first on screen")
                w.line("var entry = raw[count - 1 - i];")
            else:
                w.line("var entry = raw[i];")
            if src.intermediate is not None:
                suffix = src.field_name[len(src.intermediate) + 1:]
                w.line(f"var mid = entry.{src.intermediate};")
                w.line(f"out[i] = (mid != null) ? mid.{suffix}.toFloat() : null;")
            else:
                w.line(f"var v = entry.{src.field_name};")
                w.line("out[i] = (v != null) ? v.toFloat() : null;")

    if info.array_nullable:
        with w.block("if (raw != null)"):
            fill()
    else:
        fill()
    w.line(f"{values} = out;")
    if element.min_auto:
        w.line(f"{graph_min_field(element.id)} = WfbSeries.autoMin(out);")
    if element.max_auto:
        w.line(f"{graph_max_field(element.id)} = WfbSeries.autoMax(out);")


def _fallback_fraction(element: Progress) -> str:
    """The `progress` fallback, as a Float in 0.0-1.0.

    Two things have to be true of it, and neither is automatic.  It must be a
    **Float**: `fraction` is reassigned from `_fraction()` (a Float) in the
    branch below, and a `var` first bound to a Number makes the whole thing a
    `PolyType<Float or Number>` that `WfbArc.drawProgress`'s `Float` parameter
    rejects under `-l 3`.  And it must be **in range**: the real path is
    clamped by `WfbMath.percent`, so an unclamped fallback is the one way a
    bar could be drawn wider than its own box.  A constant is checked at build
    time (wfb/ir.py) and emitted bare; anything else is clamped on device.
    """
    fallback = element.fallback
    if fallback.is_constant:
        return f"{float(fallback.constant)}f"
    return f"WfbMath.clamp({fallback.code}, 0.0, 1.0).toFloat()"


def _fraction(element: Progress) -> str:
    return f"WfbMath.percent({element.value.code}, {element.maximum.code}) / 100.0"


