def _field(name: str) -> str:
    parts = [p for p in name.replace("-", "_").split("_") if p]
    return "font" + "".join(p[:1].upper() + p[1:] for p in parts)


def _color(expression: Expression | None) -> str:
    if expression is None:
        return "Graphics.COLOR_WHITE"
    return expression.code


def _mc_bool(value: bool) -> str:
    return "true" if value else "false"


def _loaded_fonts(resolved: ResolvedFace) -> list[str]:
    """Every font resource this view loads once in `onLayout`.

    Covers both an author's declared custom text fonts and the synthetic
    per-size icon fonts (`wfb.icons.font_key`) -- both are bitmap fonts loaded
    the same way, so one list and one loop serves both.
    """
    out: list[str] = []
    for placed in resolved.items:
        if isinstance(placed, PlacedText) and placed.font_is_custom:
            if placed.font_reference not in out:
                out.append(placed.font_reference)
        elif isinstance(placed, PlacedIcon):
            if placed.font_key not in out:
                out.append(placed.font_key)
        elif isinstance(placed, PlacedComplicationSlot):
            if placed.font_is_custom and placed.font_reference not in out:
                out.append(placed.font_reference)
            if placed.icon_font_key is not None and placed.icon_font_key not in out:
                out.append(placed.icon_font_key)
    return out


def _describe(placed) -> str:
    element = placed.element
    if isinstance(element, Shape):
        if element.shape == "polygon":
            return f"a polygon of {len(element.points)} points"
        noun = _article(element.shape.replace("_", " "))
        if element.shape in ("rectangle", "rounded_rectangle", "circle", "ellipse") \
                and not element.filled:
            return f"{noun}, outlined"
        return noun
    if isinstance(element, Text):
        return "text" if element.value is not None else "fixed text"
    if isinstance(element, Progress):
        return _article(f"{element.style} progress indicator")
    if isinstance(element, IconElement):
        if element.is_dynamic:
            return f"an icon chosen at runtime from {element.value_for.text!r}"
        return f"the {element.icon!r} icon"
    if isinstance(element, Graph):
        return f"{_article(f'{element.style} graph')} of {element.series}"
    if isinstance(element, ComplicationSlot):
        return f"a native Data-axis slot (config.data.{element.slot})"
    return element.kind


def _and_list(items) -> str:
    items = list(items)
    if len(items) <= 1:
        return "".join(items)
    return ", ".join(items[:-1]) + " and " + items[-1]


def _article(noun: str) -> str:
    return f"{'an' if noun[:1].lower() in 'aeiou' else 'a'} {noun}"


def _mc_type(value: float | McLiteral) -> str:
    if isinstance(value, McLiteral):
        return value.type
    return "Float" if isinstance(value, float) else "Number"


def _mc_number(value: float | McLiteral) -> str:
    if isinstance(value, McLiteral):
        return value.code
    return f"{value}f" if isinstance(value, float) else str(int(value))
