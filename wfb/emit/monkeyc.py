# the read plan: which API calls happen, and where


class ReadPlan:
    """Decides which reader locals each element needs, and hoists the reads.

    Sources are grouped by reader so that ``ActivityMonitor.getInfo()`` is called
    once per frame no matter how many fields read off it, and every nullable
    field becomes a named local that the element's guard narrows.
    """

    def __init__(self, resolved: ResolvedFace) -> None:
        self.resolved = resolved
        self.modules: set[str] = set()
        self.barrel: set[str] = set(resolved.face.barrel_functions())
        #: Every source an element touches, for reader hoisting.
        self._per_element: dict[str, list[str]] = {}
        #: The subset referenced by compiled expressions, which read through a
        #: named local.  Format specs read their reader directly instead.
        self._bound: dict[str, list[str]] = {}
        self._readers_for_mode: dict[str, list[str]] = {}
        self._analyse()
        if self.slow_readers():
            self.modules.add("Toybox.Time")  # Time.now(), for WfbCache.stale()

    def _analyse(self) -> None:
        for placed in self.resolved.items:
            paths: list[str] = []
            for expression in placed.element.expressions():
                self.modules |= set(expression.modules)
                for path in expression.sources:
                    if path not in paths:
                        paths.append(path)
            # A time format reads the clock (and, for %h, the device settings)
            # even though the format string names no source.
            element = placed.element
            format_paths: list[str] = []
            if (isinstance(element, Text) and element.format
                    and formatting.is_time_spec(element.format)):
                # A date format reads the calendar; a time format reads the clock,
                # and %h additionally reads the 12/24-hour setting.
                if element.value is not None and element.value.value.type is Type.DATE:
                    format_paths.append("date.today")
                else:
                    format_paths.append("time.clock")
                    if "%h" in element.format:
                        format_paths.append("device.is_24_hour")
            self._bound[placed.id] = list(paths)
            paths = paths + [p for p in format_paths if p not in paths]
            self._per_element[placed.id] = paths
            for path in paths:
                self.modules.add(READERS[catalog.CATALOG[path].reader].module)

        for mode in ("active", "low_power", "always_on"):
            readers: list[str] = []
            for placed in self.resolved.items:
                if mode not in placed.element.modes:
                    continue
                for path in self._per_element[placed.id]:
                    reader = catalog.CATALOG[path].reader
                    if reader not in readers:
                        readers.append(reader)
            self._readers_for_mode[mode] = readers

    # -- emission ---------------------------------------------------------

    def slow_readers(self) -> list[str]:
        """Reader names on `Tier.SLOW` this design actually reads.

        Always found under ``active`` mode only: `wfb.ir`'s `_check_tiers`
        rejects binding a non-frame-tier source from a `low_power` or
        `always_on` element, so there is nothing to check here -- a slow
        reader appearing under any other mode would be an IR bug, not a
        design mistake, and `emit_reads` below is written on that assumption.
        """
        return sorted({name for name in self._readers_for_mode.get("active", [])
                       if READERS[name].tier is not Tier.FRAME})

    def emit_reads(self, w: Writer, mode: str) -> None:
        readers = self._readers_for_mode.get(mode) or []
        if not readers:
            return
        tier_note = "frame-tier reads only" if mode != "active" else "data for this frame"
        w.comment(tier_note)
        for name in readers:
            reader = READERS[name]
            if reader.tier is Tier.FRAME:
                w.line(f"var {reader.name} = {reader.call};")
                continue
            # A `slow`-tier reader is cached in a view field instead of called
            # fresh every frame -- see WfbCache.mc and `_emit_cache_fields`.
            cache = f"_{reader.name}Cache"
            cache_time = f"_{reader.name}CacheTime"
            with w.block(f"if (WfbCache.stale({cache_time}, {reader.ttl_seconds}))"):
                w.line(f"{cache} = {reader.call};")
                w.line(f"{cache_time} = Time.now().value();")
            w.line(f"var {reader.name} = {cache};")

    def parameters(self, placed) -> str:
        params = []
        for name in self._readers_used_by(placed):
            reader = READERS[name]
            params.append(f", {reader.name} as {reader.monkeyc_type}")
        return "".join(params)

    def arguments(self, placed) -> str:
        return "".join(f", {READERS[name].name}" for name in self._readers_used_by(placed))

    def guards(self, placed) -> list[str]:
        """Locals the element must null-check, declared in dependency order."""
        from ..ir import local_name

        names: list[str] = []
        for path in self._bound[placed.id]:
            source = catalog.CATALOG[path]
            if source.guard_needed and source.field_name is not None:
                names.append(local_name(path))
        return names

    def declarations(self, placed) -> list[tuple[str, str]]:
        from ..ir import local_name

        out: list[tuple[str, str]] = []
        for path in self._bound[placed.id]:
            source = catalog.CATALOG[path]
            if source.field_name is None:
                continue
            reader = READERS[source.reader]
            read = source.read_expr
            guard_parts = []
            if reader.nullable:
                # The reader itself can be absent -- Activity.getActivityInfo()
                # returns null when there is no activity -- so the field cannot
                # be dereferenced unconditionally.  Narrowing here keeps the
                # element's own `when_absent` guard below unchanged: an absent
                # reader and an absent field are the same thing to the design.
                guard_parts.append(f"{reader.name} != null")
            if source.array_guard is not None:
                # An Array being non-null does not mean it has an element at
                # this index -- a forecast provider can return fewer days than
                # asked for. Short-circuit `&&` means the null check above (if
                # any) always runs first, so `.size()` never hits a null array.
                guard_parts.append(source.array_guard)
            if guard_parts:
                read = f"({' && '.join(guard_parts)}) ? {read} : null"
            out.append((local_name(path), read))
        return out

    def _readers_used_by(self, placed) -> list[str]:
        readers: list[str] = []
        for path in self._per_element[placed.id]:
            reader = catalog.CATALOG[path].reader
            if reader not in readers:
                readers.append(reader)
        return readers

    def sources_for(self, placed) -> list[str]:
        return self._per_element[placed.id]


# --------------------------------------------------------------------------
# naming and small helpers


def _const_prefix(element_id: str) -> str:
    out = []
    for index, char in enumerate(element_id):
        if char.isupper() and index and not element_id[index - 1].isupper():
            out.append("_")
        out.append(char.upper() if char.isalnum() else "_")
    return "".join(out)


def _method(element_id: str) -> str:
    parts = [p for p in element_id.replace("-", "_").split("_") if p]
    return "draw" + "".join(p[:1].upper() + p[1:] for p in parts)


def _field(name: str) -> str:
    parts = [p for p in name.replace("-", "_").split("_") if p]
    return "font" + "".join(p[:1].upper() + p[1:] for p in parts)


def _color(expression: Expression | None) -> str:
    if expression is None:
        return "Graphics.COLOR_WHITE"
    return expression.code


def _loaded_fonts(resolved: ResolvedFace) -> list[str]:
    """Every font resource this view loads once in `onLayout`.

    Covers both an author's declared custom text fonts and the synthetic
    per-size icon fonts (`wfb.icons.font_key`) -- both are bitmap fonts loaded
    the same way, so one list and one loop serves both.
    """
    out: list[str] = []
    for placed in resolved.items:
        if isinstance(placed, PlacedText) and placed.font_is_custom:
            if placed.font_reference not in out:
                out.append(placed.font_reference)
        elif isinstance(placed, PlacedIcon):
            if placed.font_key not in out:
                out.append(placed.font_key)
    return out


def _describe(placed) -> str:
    element = placed.element
    if isinstance(element, Shape):
        return _article(element.shape.replace("_", " "))
    if isinstance(element, Text):
        return "text" if element.value is not None else "fixed text"
    if isinstance(element, Progress):
        return _article(f"{element.style} progress indicator")
    if isinstance(element, IconElement):
        if element.is_dynamic:
            return f"an icon chosen at runtime from {element.value_for.text!r}"
        return f"the {element.icon!r} icon"
    return element.kind


def _and_list(items) -> str:
    items = list(items)
    if len(items) <= 1:
        return "".join(items)
    return ", ".join(items[:-1]) + " and " + items[-1]


def _article(noun: str) -> str:
    return f"{'an' if noun[:1].lower() in 'aeiou' else 'a'} {noun}"


def _mc_type(value: float) -> str:
    return "Float" if isinstance(value, float) else "Number"


def _mc_number(value: float) -> str:
    return f"{value}f" if isinstance(value, float) else str(int(value))
