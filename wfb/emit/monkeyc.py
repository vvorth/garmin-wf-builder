# one method per element


def _emit_element_method(w: Writer, resolved: ResolvedFace, placed, plan: "ReadPlan",
                         antialias_default: bool | None = None) -> None:
    element = placed.element
    w.doc(_method_doc(placed))
    signature = f"private function {_method(placed.id)}(dc as Dc{plan.parameters(placed)}) as Void"
    # 'placeholder'/'fallback' are policies for the *value* -- a substitute
    # text or fill fraction takes over instead of the element simply not
    # drawing.  They say nothing about a nullable colour, track colour or
    # max: there is no placeholder for a colour, so those always get a real
    # guard regardless of which policy the value chose (Bug 5).
    substitutes_value = (
        isinstance(placed, (PlacedText, PlacedProgress))
        and getattr(element, "when_absent", None) in ("placeholder", "fallback")
    )
    with w.block(signature):
        declarations = plan.declarations(placed)
        if declarations:
            w.comment("the values this element is bound to")
            for name, read in declarations:
                w.line(f"var {name} = {read};")
            w.blank()
        _emit_visible_guard(w, placed, plan)
        if isinstance(placed, PlacedCarousel):
            # Deliberately no element-level guard.  Every other element hides
            # as a whole when a binding is absent, but a carousel's bindings
            # belong to *items*: one absent reading blanks one slot's text and
            # leaves the row, its icons and its hold zones exactly where they
            # were.  Each item's own policy is applied inside the switch below.
            _emit_carousel(w, placed, plan)
            return
        value_guards = plan.value_guards(placed)
        if substitutes_value:
            other_guards = plan.other_guards(placed)
            if other_guards:
                _emit_guard(w, placed, other_guards,
                           note="hide -- a nullable colour/track_color/max always hides "
                                "the element, regardless of the value's own when_absent")
        else:
            other_guards = plan.guards(placed)
            if other_guards:
                _emit_guard(w, placed, other_guards)
        # Anti-aliasing only ever varies for a shape or progress element -- text
        # and icons draw glyphs, whose anti-aliasing is a font-resource matter
        # (baked at build time, see wfb.icons/wfb.fonts), not a per-frame Dc
        # call, so they emit no setAntiAlias-related code at all.  The toggle
        # brackets only the actual drawing call below, deliberately *after*
        # every guard above: a guard can return early, and doing this any
        # earlier would leave the Dc's anti-alias state changed on a frame
        # that drew nothing, breaking the invariant every other draw method
        # relies on -- that Dc is already at the face default by the time its
        # own drawing runs.
        overrides_antialias = (
            antialias_default is not None
            and isinstance(placed, (PlacedShape, PlacedProgress, PlacedGraph))
            and element.resolved_antialias != antialias_default
        )
        if overrides_antialias:
            w.comment(f"antialias: {_mc_bool(element.resolved_antialias)}")
            w.line(f"applyAntiAlias(dc, {_mc_bool(element.resolved_antialias)});")
        if isinstance(placed, PlacedShape):
            _emit_shape(w, placed)
        elif isinstance(placed, PlacedText):
            _emit_text(w, resolved, placed, value_guards)
        elif isinstance(placed, PlacedProgress):
            _emit_progress(w, placed, value_guards)
        elif isinstance(placed, PlacedIcon):
            _emit_icon(w, placed)
        elif isinstance(placed, PlacedCarousel):
            _emit_carousel(w, placed, plan)
        elif isinstance(placed, PlacedGraph):
            _emit_graph(w, placed)
        if overrides_antialias:
            w.line(f"applyAntiAlias(dc, {_mc_bool(antialias_default)});")


def _method_doc(placed) -> str:
    element = placed.element
    lines = [f"`{element.id}` -- {_describe(placed)}."]
    # `visible:` gets its own line below rather than being listed as a
    # binding: it says when the element draws, not what it shows.
    bindings = [e.text for e in element.expressions()
                if e.sources and e is not element.visible]
    if bindings:
        lines.append("")
        lines.append("Bound to " + _and_list(f"`{text}`" for text in bindings) + ".")
    if element.visible is not None:
        lines.append(f"Drawn only when `{element.visible.text}` "
                     "(absent readings count as hidden).")
    policy = getattr(element, "when_absent", None)
    if policy:
        lines.append(f"When the value is absent: {policy}.")
    modes = ", ".join(element.modes)
    lines.append(f"Drawn in: {modes}.")
    return "\n".join(lines)


def _negated(expression) -> str:
    """The Monkey C for "this condition does **not** hold".

    A condition that is itself a `not` is un-negated rather than wrapped: the
    guard for `visible: "not system.charging"` reads `if (systemCharging)`, not
    `if (!(!systemCharging))`, which is not something a person would have
    written.  `expr.emit` renders a `not` as exactly `(!<operand>)`, so this is
    a slice off a known shape rather than a second, drifting emitter.
    """
    code = expression.code
    node = expression.ast
    if isinstance(node, expr.Unary) and node.op == "not":
        assert code.startswith("(!") and code.endswith(")"), code
        return code[2:-1]
    return f"!{_negatable(code)}"


def _negatable(code: str) -> str:
    """``code`` wrapped in parentheses unless it already is one group.

    `expr.emit` parenthesises every operator it emits, so a condition almost
    always arrives as `(a < b)` and `!((a < b))` would be the honest but
    unreadable result of wrapping it again.  Only a single enclosing group
    counts: `(a) || (b)` starts and ends with a bracket without being one.
    """
    if not (code.startswith("(") and code.endswith(")")):
        return f"({code})"
    depth = 0
    for index, char in enumerate(code):
        if char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
            if depth == 0 and index != len(code) - 1:
                return f"({code})"
    return code


def _emit_visible_guard(w: Writer, placed, plan: "ReadPlan") -> None:
    """`visible:` -- one guard covering both absence and the condition.

    Emitted before every other guard, and before a carousel's own early
    return, because visibility gates the element as a whole: a hidden carousel
    draws no row at all (its hold zones are another matter -- see
    `docs/limitations.md`).

    The shape is `if (x == null || !(cond)) { return; }`, one `== null` per
    nullable local the condition reads.  That is "absent means hidden" written
    out: there is no `when_absent:` for existence, so an unavailable reading
    and a false condition are the same outcome and belong in the same test.
    Verified that `monkeyc` narrows the local across the `||` -- the condition
    on the right dereferences it -- with a real warning-free `-w` build under
    the jungle's `project.typecheck = strict`.

    A condition that folded to a build-time constant is handled honestly
    rather than specially: a constant `true` emits nothing (there is nothing
    to check), and a constant `false` emits the guard as written, which
    `monkeyc` accepts without an unreachable-code warning (verified the same
    way) and `-O 3z` folds away.  The `dead-element` lint is what tells the
    author about the second case.
    """
    element = placed.element
    expression = element.visible
    if expression is None:
        return
    if expression.constant is not None and expression.constant:
        w.comment(f"visible: {expression.text} -- always true, nothing to check")
        w.blank()
        return
    parts = [f"{name} == null" for name in plan.visible_guards(placed)]
    parts.append(_negated(expression))
    w.comment(f"visible: {expression.text}"
              + (" -- absent means hidden" if len(parts) > 1 else ""))
    with w.block(f"if ({' || '.join(parts)})"):
        w.line("return;")
    w.blank()


def _emit_guard(w: Writer, placed, guards: list[str], note: str | None = None) -> None:
    """Emit the null check, and say which `when_absent:` produced it.

    ``note`` overrides the default "when_absent: <policy>" comment for the
    case (Bug 5) where the guard covers only bindings the value's own policy
    does not govern -- a nullable colour still just hides the element even
    when the value itself falls back to a placeholder.
    """
    element = placed.element
    condition = " || ".join(f"{name} == null" for name in guards)
    w.comment(note if note is not None else f"when_absent: {getattr(element, 'when_absent', None) or 'hide'}")
    with w.block(f"if ({condition})"):
        w.line("return;")
    w.blank()


def _emit_shape(w: Writer, placed: PlacedShape) -> None:
    element = placed.element
    prefix = _const_prefix(placed.id)
    w.line(f"dc.setColor({_color(element.color)}, Graphics.COLOR_TRANSPARENT);")
    if element.shape == "rectangle":
        if element.filled:
            w.line(f"dc.fillRectangle(Layout.{prefix}_X, Layout.{prefix}_Y,")
            w.line(f"                 Layout.{prefix}_WIDTH, Layout.{prefix}_HEIGHT);")
        else:
            w.line(f"dc.setPenWidth(Layout.{prefix}_THICKNESS);")
            w.line(f"dc.drawRectangle(Layout.{prefix}_X, Layout.{prefix}_Y,")
            w.line(f"                 Layout.{prefix}_WIDTH, Layout.{prefix}_HEIGHT);")
            w.line("dc.setPenWidth(1);")
    elif element.shape == "rounded_rectangle":
        if element.filled:
            w.line(f"dc.fillRoundedRectangle(Layout.{prefix}_X, Layout.{prefix}_Y,")
            w.line(f"                        Layout.{prefix}_WIDTH, Layout.{prefix}_HEIGHT,")
            w.line(f"                        Layout.{prefix}_CORNER);")
        else:
            w.line(f"dc.setPenWidth(Layout.{prefix}_THICKNESS);")
            w.line(f"dc.drawRoundedRectangle(Layout.{prefix}_X, Layout.{prefix}_Y,")
            w.line(f"                        Layout.{prefix}_WIDTH, Layout.{prefix}_HEIGHT,")
            w.line(f"                        Layout.{prefix}_CORNER);")
            w.line("dc.setPenWidth(1);")
    elif element.shape == "arc":
        # The same barrel call a `progress` track uses, so the two arcs cannot
        # disagree about the angle convention or about the full-circle case
        # (drawArc draws a complete circle when start == end).
        w.line(
            f"WfbArc.drawSpan(dc, Layout.{prefix}_CX, Layout.{prefix}_CY, "
            f"Layout.{prefix}_RADIUS,"
        )
        w.line(
            f"                Layout.{prefix}_THICKNESS, Layout.{prefix}_START, "
            f"Layout.{prefix}_SWEEP);"
        )
    elif element.shape == "ellipse":
        if element.filled:
            w.line(f"dc.fillEllipse(Layout.{prefix}_CX, Layout.{prefix}_CY,")
            w.line(f"               Layout.{prefix}_RX, Layout.{prefix}_RY);")
        else:
            w.line(f"dc.setPenWidth(Layout.{prefix}_THICKNESS);")
            w.line(f"dc.drawEllipse(Layout.{prefix}_CX, Layout.{prefix}_CY,")
            w.line(f"               Layout.{prefix}_RX, Layout.{prefix}_RY);")
            w.line("dc.setPenWidth(1);")
    elif element.shape == "polygon":
        # There is no drawPolygon in Dc, only fillPolygon -- `filled: false` is
        # rejected in wfb/ir.py rather than silently filled here.
        w.line(f"dc.fillPolygon(Layout.{prefix}_POINTS);")
    elif element.shape == "circle":
        if element.filled:
            w.line(f"dc.fillCircle(Layout.{prefix}_CX, Layout.{prefix}_CY, Layout.{prefix}_RADIUS);")
        else:
            w.line(f"dc.setPenWidth({placed.thickness});")
            w.line(f"dc.drawCircle(Layout.{prefix}_CX, Layout.{prefix}_CY, Layout.{prefix}_RADIUS);")
            w.line("dc.setPenWidth(1);")
    elif element.shape == "line":
        w.line(f"dc.setPenWidth(Layout.{prefix}_THICKNESS);")
        w.line(
            f"dc.drawLine(Layout.{prefix}_CX, Layout.{prefix}_CY, "
            f"Layout.{prefix}_END_X, Layout.{prefix}_END_Y);"
        )
        w.line("dc.setPenWidth(1);")


def _emit_text(w: Writer, resolved: ResolvedFace, placed: PlacedText, guards: list[str]) -> None:
    element = placed.element
    if element.literal is not None:
        _emit_text_draw(w, placed, f'"{element.literal}"')
        return

    value_code = formatting.emit(
        element.format or "{}",
        element.value.code,
        element.value.value.type,
    )
    if element.when_absent == "placeholder" and guards:
        # Build the string once rather than duplicating the draw call in both
        # branches: the placeholder is a different *value*, not a different draw.
        w.comment(f"when_absent: placeholder")
        available = " && ".join(f"{name} != null" for name in guards)
        w.line(f'var text = "{element.placeholder}";')
        with w.block(f"if ({available})"):
            w.line(f"text = {value_code};")
        w.blank()
        _emit_text_draw(w, placed, "text")
        return
    if element.when_absent == "fallback" and guards:
        # Same shape as placeholder above, except the substitute is itself a
        # compiled expression rather than a literal string, so it is run
        # through the same format spec the real value uses.
        fallback_code = formatting.emit(
            element.format or "{}",
            element.fallback.code,
            element.fallback.value.type,
        )
        w.comment("when_absent: fallback")
        available = " && ".join(f"{name} != null" for name in guards)
        w.line(f"var text = {fallback_code};")
        with w.block(f"if ({available})"):
            w.line(f"text = {value_code};")
        w.blank()
        _emit_text_draw(w, placed, "text")
        return
    _emit_text_draw(w, placed, value_code)


def _emit_text_draw(w: Writer, placed: PlacedText, value_code: str) -> None:
    element = placed.element
    prefix = _const_prefix(placed.id)
    justify = " | ".join(f"Graphics.{flag}" for flag in placed.justify)
    if placed.font_is_custom:
        w.line(f"var font = _{_field(placed.font_reference)};")
        with w.block("if (font == null)"):
            w.line("return;  // the font resource failed to load")
        w.blank()
        font_expr = "font"
    else:
        font_expr = f"Graphics.{placed.font_reference}"
    w.line(f"dc.setColor({_color(element.color)}, Graphics.COLOR_TRANSPARENT);")
    w.line(f"dc.drawText(Layout.{prefix}_X, Layout.{prefix}_Y, {font_expr},")
    w.line(f"            {value_code},")
    w.line(f"            {justify});")


def _emit_progress(w: Writer, placed: PlacedProgress, guards: list[str]) -> None:
    element = placed.element
    prefix = _const_prefix(placed.id)
    fraction_expr = _fraction(element)
    if element.when_absent == "fallback" and guards:
        # The fill fraction falls back, not the raw value/max -- 'fallback:'
        # supplies a number in the same 0.0-1.0 range _fraction() computes, so
        # it slots into exactly the same drawProgress/fillRectangle call the
        # real reading would have used.  (This is why a `progress` fallback
        # means something different from a `text` one, which supplies the
        # *value* and is then formatted; for progress either half of the pair
        # can be the absent reading, so the outcome is the only well-defined
        # thing to substitute.  wfb/ir.py checks it is in range and
        # wfb/preview.py renders the same substitution.)
        w.comment("when_absent: fallback")
        available = " && ".join(f"{name} != null" for name in guards)
        w.line(f"var fraction = {_fallback_fraction(element)};")
        with w.block(f"if ({available})"):
            w.line(f"fraction = {fraction_expr};")
        w.blank()
        fraction_expr = "fraction"
    if element.style == "arc":
        if element.track_color is not None:
            w.comment("the unfilled track")
            w.line(f"dc.setColor({_color(element.track_color)}, Graphics.COLOR_TRANSPARENT);")
            w.line(
                f"WfbArc.drawSpan(dc, Layout.{prefix}_CX, Layout.{prefix}_CY, "
                f"Layout.{prefix}_RADIUS,"
            )
            w.line(
                f"                Layout.{prefix}_THICKNESS, Layout.{prefix}_START, "
                f"Layout.{prefix}_SWEEP);"
            )
            w.blank()
        w.comment("the filled portion")
        w.line(f"dc.setColor({_color(element.color)}, Graphics.COLOR_TRANSPARENT);")
        w.line(
            f"WfbArc.drawProgress(dc, Layout.{prefix}_CX, Layout.{prefix}_CY, "
            f"Layout.{prefix}_RADIUS,"
        )
        w.line(
            f"                    Layout.{prefix}_THICKNESS, Layout.{prefix}_START, "
            f"Layout.{prefix}_SWEEP,"
        )
        w.line(f"                    {fraction_expr});")
        return

    if element.track_color is not None:
        w.line(f"dc.setColor({_color(element.track_color)}, Graphics.COLOR_TRANSPARENT);")
        w.line(
            f"dc.fillRectangle(Layout.{prefix}_X, Layout.{prefix}_Y, "
            f"Layout.{prefix}_WIDTH, Layout.{prefix}_HEIGHT);"
        )
        w.blank()
    w.line(f"var filled = (Layout.{prefix}_WIDTH * {fraction_expr}).toNumber();")
    w.line(f"dc.setColor({_color(element.color)}, Graphics.COLOR_TRANSPARENT);")
    w.line(
        f"dc.fillRectangle(Layout.{prefix}_X, Layout.{prefix}_Y, filled, Layout.{prefix}_HEIGHT);"
    )


def _emit_icon(w: Writer, placed: PlacedIcon) -> None:
    """A `drawText` call against the icon's baked glyph -- see `wfb.icons`:
    an icon is a one-character string drawn with a bitmap font, the same
    mechanism any other bound text uses, not a hand-drawn shape.

    A *dynamic* icon (`icon_for:`) draws the same way, except the glyph
    string is resolved in two steps at runtime instead of being a literal
    baked in at build time: `WfbWeather.chooseIcon` picks a catalogue *name*
    from the bound value, and `IconGlyphs.glyph` (generated per project,
    directly from `wfb.icon_catalog.CATALOG`) turns that name into the actual
    character -- the same table any static icon's build-time lookup uses, not
    a second, weather-only one. The font still has every glyph that call
    could return, baked in ahead of time (`wfb.emit.resources.icon_font_specs`).
    """
    element = placed.element
    prefix = _const_prefix(placed.id)
    w.line(f"var font = _{_field(placed.font_key)};")
    with w.block("if (font == null)"):
        w.line("return;  // the icon font resource failed to load")
    w.blank()
    if element.is_dynamic:
        from ..ir import local_name

        condition_local = local_name(element.value_for.sources[0])
        w.comment(f"{element.value_for.text!r} -> a name (WfbWeather) -> a glyph (IconGlyphs)")
        glyph_expr = f"IconGlyphs.glyph(WfbWeather.chooseIcon({condition_local}))"
    else:
        w.comment(f"{element.icon!r}")
        glyph_expr = f'"{element.codepoint}"'
    w.line(f"dc.setColor({_color(element.color)}, Graphics.COLOR_TRANSPARENT);")
    w.line(f"dc.drawText(Layout.{prefix}_CX, Layout.{prefix}_CY, font,")
    w.line(f"            {glyph_expr},")
    w.line("            Graphics.TEXT_JUSTIFY_CENTER | Graphics.TEXT_JUSTIFY_VCENTER);")


def _emit_carousel(w: Writer, placed: PlacedCarousel, plan: "ReadPlan") -> None:
    """The icon row, then the selected item's reading.

    The row is a loop over *slots* with a switch on the item that lands in
    each, rather than a loop over items: which item sits in which slot changes
    every time the wearer moves the carousel, and the slide offset applies to
    the slot, not the item.
    """
    element = placed.element
    prefix = _const_prefix(placed.id)
    index = carousel_index_field(element.id)
    count = len(element.items)
    slide = (carousel_slide_field(element.id) if element.animate > 0 else None)
    active = _color(element.color)
    inactive = _color(element.inactive_color) if element.inactive_color is not None else active

    if element.slots > 1:
        reach = element.slots // 2
        w.comment(f"the icon row: {element.slots} slots, the centred one selected")
        with w.block(f"for (var slot = -{reach}; slot <= {reach}; slot += 1)"):
            w.line(f"var item = ({index} + slot + {count}) % {count};")
            offset = f" - {slide}" if slide else ""
            w.line(f"var x = Layout.{prefix}_CX + slot * Layout.{prefix}_PITCH{offset};")
            if inactive != active:
                w.line(f"dc.setColor(slot == 0 ? {active} : {inactive}, "
                       "Graphics.COLOR_TRANSPARENT);")
            else:
                w.line(f"dc.setColor({active}, Graphics.COLOR_TRANSPARENT);")
            _emit_carousel_glyph_switch(w, placed, "item", "x")
    else:
        w.comment("one slot: only the selected item is drawn")
        w.line(f"dc.setColor({active}, Graphics.COLOR_TRANSPARENT);")
        _emit_carousel_glyph_switch(w, placed, index, f"Layout.{prefix}_CX")
    w.blank()

    w.comment("the selected item's reading")
    w.line('var text = "";')
    with w.block(f"switch ({index})"):
        for item_placed, item in zip(placed.items, element.items):
            w.line(f"// item {item_placed.index}: {item.icon}"
                   + (f" -- {item.value.text}" if item.value is not None else ""))
            with w.block(f"case {item_placed.index}:"):
                _emit_carousel_item_text(w, item, plan)
                w.line("break;")
    w.blank()
    if placed.value_font_is_custom:
        w.line(f"var valueFont = _{_field(placed.value_font_reference)};")
        with w.block("if (valueFont == null)"):
            w.line("return;  // the font resource failed to load")
        w.blank()
        font_expr = "valueFont"
    else:
        font_expr = f"Graphics.{placed.value_font_reference}"
    value_color = (_color(element.value_color) if element.value_color is not None else active)
    w.line(f"dc.setColor({value_color}, Graphics.COLOR_TRANSPARENT);")
    w.line(f"dc.drawText(Layout.{prefix}_VALUE_X, Layout.{prefix}_VALUE_Y, {font_expr}, text,")
    w.line("            Graphics.TEXT_JUSTIFY_CENTER | Graphics.TEXT_JUSTIFY_VCENTER);")


def _emit_carousel_glyph_switch(w: Writer, placed: PlacedCarousel,
                                selector: str, x_expr: str) -> None:
    """Draw whichever item's glyph belongs at `x_expr`.

    Each item gets its own font resource because `wfb.icons.bake_size` picks a
    nominal size per glyph -- the vendored font's aggregated icon sets pad
    their glyphs differently inside the em-square, so one nominal size does not
    give them all the same ink height.
    """
    prefix = _const_prefix(placed.id)
    with w.block(f"switch ({selector})"):
        for item_placed, item in zip(placed.items, placed.element.items):
            w.line(f"// item {item_placed.index}: {item.icon}")
            with w.block(f"case {item_placed.index}:"):
                field = f"_{_field(item_placed.font_key)}"
                w.line(f"var glyphFont = {field};")
                with w.block("if (glyphFont != null)"):
                    w.line(f"dc.drawText({x_expr}, Layout.{prefix}_CY, glyphFont,")
                    w.line(f'            "{item_placed.codepoint}",')
                    w.line("            Graphics.TEXT_JUSTIFY_CENTER "
                           "| Graphics.TEXT_JUSTIFY_VCENTER);")
                w.line("break;")


def _emit_carousel_item_text(w: Writer, item, plan: "ReadPlan") -> None:
    """One item's reading, with that item's own `when_absent:` policy.

    Scoped to the item on purpose: this is the whole reason a carousel skips
    the element-level guard every other element gets.
    """
    from ..ir import local_name

    if item.value is None:
        w.line('text = "";')
        return
    value_code = formatting.emit(item.format or "{}", item.value.code,
                                item.value.value.type)
    guards = [local_name(path) for path in item.value.sources
              if catalog.CATALOG[path].guard_needed]
    if not guards:
        w.line(f"text = {value_code};")
        return
    available = " && ".join(f"{name} != null" for name in guards)
    if item.when_absent == "placeholder":
        w.comment("when_absent: placeholder")
        w.line(f'text = "{item.placeholder}";')
    elif item.when_absent == "fallback":
        w.comment("when_absent: fallback")
        w.line("text = " + formatting.emit(item.format or "{}", item.fallback.code,
                                           item.fallback.value.type) + ";")
    else:
        w.comment("when_absent: hide -- this slot's reading is blank, the icon stays")
        w.line('text = "";')
    with w.block(f"if ({available})"):
        w.line(f"text = {value_code};")


def _emit_graph_fields(w: Writer, graphs: list) -> None:
    """One cached series (plus its auto bounds, where asked for) per `graph`.

    Rebuilt once a minute (`_emit_graph`'s cadence check), not per frame --
    see `runtime-lib/WfbSeries.mc`'s module docstring for why this is not the
    TTL cache this project deleted.
    """
    if not graphs:
        return
    for placed in graphs:
        element = placed.element
        w.doc(f"`{element.id}`: the cached {element.series!r} series.")
        w.line(f"private var {graph_series_field(element.id)} as Array<Float?> = "
               "[] as Array<Float?>;")
        # heart_rate's auto bound comes from the iterator's own getMin/getMax,
        # which is a Number; every other series' comes from WfbSeries.autoMin/
        # autoMax over the collected Array<Float?>, which is a Float.
        auto_type = ("Number" if element.series_def is not None
                     and element.series_def.acquisition is Acquisition.HEART_RATE
                     else "Float")
        zero = "0" if auto_type == "Number" else "0.0"
        if element.min_auto:
            w.line(f"private var {graph_min_field(element.id)} as {auto_type} = {zero};")
        if element.max_auto:
            w.line(f"private var {graph_max_field(element.id)} as {auto_type} = {zero};")
        w.doc(f"`{element.id}`: the minute this series was last rebuilt.")
        w.line(f"private var {graph_built_field(element.id)} as Number = -1;")
    w.blank()


def _emit_graph(w: Writer, placed: PlacedGraph) -> None:
    """The rebuild-cadence check, then one drawing call per `style:`.

    The check runs here rather than unconditionally in `onUpdate` -- after
    the element's own guards, alongside every other kind's actual drawing --
    so a hidden graph does not pay for a rebuild nobody will see this frame.
    """
    element = placed.element
    prefix = _const_prefix(placed.id)
    built = graph_built_field(element.id)
    w.comment("the sample interval here is minutes, so rebuilding more often than")
    w.comment("once a minute could not show anything new (WfbSeries.mc's docstring)")
    with w.block(f"if (System.getClockTime().min != {built})"):
        w.line(f"{built} = System.getClockTime().min;")
        w.line(f"{graph_rebuild_method(element.id)}();")
    w.blank()

    values = graph_series_field(element.id)
    lo = (f"{graph_min_field(element.id)}.toFloat()" if element.min_auto
          else f"({element.min.code}).toFloat()")
    hi = (f"{graph_max_field(element.id)}.toFloat()" if element.max_auto
          else f"({element.max.code}).toFloat()")
    w.line(f"dc.setColor({_color(element.color)}, Graphics.COLOR_TRANSPARENT);")
    if element.style == "line":
        w.line(f"WfbSeries.drawLine(dc, Layout.{prefix}_X, Layout.{prefix}_Y, "
               f"Layout.{prefix}_WIDTH, Layout.{prefix}_HEIGHT,")
        w.line(f"                   Layout.{prefix}_THICKNESS, {values}, {lo}, {hi});")
    elif element.style == "area":
        w.line(f"WfbSeries.drawArea(dc, Layout.{prefix}_X, Layout.{prefix}_Y, "
               f"Layout.{prefix}_WIDTH, Layout.{prefix}_HEIGHT,")
        w.line(f"                   {values}, {lo}, {hi});")
    else:  # bars
        w.line(f"WfbSeries.drawBars(dc, Layout.{prefix}_X, Layout.{prefix}_Y, "
               f"Layout.{prefix}_WIDTH, Layout.{prefix}_HEIGHT,")
        w.line(f"                   Layout.{prefix}_BAR_WIDTH, {values}, {lo}, {hi});")


def _emit_graph_rebuild(w: Writer, placed: PlacedGraph) -> None:
    """`rebuild<Id>()` -- recompute one graph's cached series.

    `heart_rate` is the one hand-written shape in `WfbSeries.mc`, shared by
    every design that plots it; every other series loops over its own array
    here, generated per project, because the field a design binds
    (`day.steps` vs. `day.calories`, `hour.temperature` vs. `hour.uvIndex`)
    varies and Monkey C offers no way to pass one.
    """
    element = placed.element
    src = element.series_def
    w.blank()
    w.doc(f"Recompute `{element.id}`'s {element.series!r} series.")
    with w.block(f"private function {graph_rebuild_method(element.id)}() as Void"):
        if src.acquisition is Acquisition.HEART_RATE:
            _emit_hr_rebuild(w, element)
        else:
            _emit_array_rebuild(w, element, src)


def _emit_hr_rebuild(w: Writer, element: Graph) -> None:
    """`heart_rate`: acquire the iterator, take its free min/max, then hand
    it to `WfbSeries` to bin (a duration range) or collect (a count range).

    `getMin()`/`getMax()` must run before the iterator is consumed by
    `next()` -- both queries are metadata on the iterator, not a cursor
    advance, confirmed against the reference probe
    (`docs/research/probes/graph-series/`), which calls them in exactly this
    order for exactly this reason.
    """
    period = (f"new Time.Duration({element.range_value})" if element.range_kind == "duration"
              else str(element.range_value))
    w.line(f"var iterator = ActivityMonitor.getHeartRateHistory({period}, false);")
    if element.min_auto:
        w.line("var lo = iterator.getMin();")
        w.line(f"{graph_min_field(element.id)} = (lo != null) ? lo : 0;")
    if element.max_auto:
        w.line("var hi = iterator.getMax();")
        w.line(f"{graph_max_field(element.id)} = (hi != null) ? hi : 0;")
    if element.range_kind == "duration":
        w.line(f"{graph_series_field(element.id)} = WfbSeries.binHeartRate("
               f"iterator, {element.sample_count}, {element.range_value});")
    else:
        w.line(f"{graph_series_field(element.id)} = WfbSeries.collectHeartRate(iterator);")


def _emit_array_rebuild(w: Writer, element: Graph, src) -> None:
    """`steps`/`calories`/.../`daily_precipitation_chance`: one short array,
    read into a fixed-size `Array<Float?>` -- `null` past the end when the
    acquired array is shorter than the requested sample count, which is the
    ordinary case for a design new enough not to have 7 days of history yet.
    """
    info = series.ACQUISITION[src.acquisition]
    n = element.sample_count
    values = graph_series_field(element.id)
    w.line(f"var raw = {info.call};")
    w.line(f"var out = new [{n}] as Array<Float?>;")
    with w.block(f"for (var i = 0; i < {n}; i += 1)"):
        w.line("out[i] = null;")

    def fill() -> None:
        w.line(f"var count = WfbSeries.min({n}, raw.size());")
        with w.block("for (var i = 0; i < count; i += 1)"):
            if info.newest_first:
                w.comment("most recent first on the wire; oldest first on screen")
                w.line("var entry = raw[count - 1 - i];")
            else:
                w.line("var entry = raw[i];")
            if src.intermediate is not None:
                suffix = src.field_name[len(src.intermediate) + 1:]
                w.line(f"var mid = entry.{src.intermediate};")
                w.line(f"out[i] = (mid != null) ? mid.{suffix}.toFloat() : null;")
            else:
                w.line(f"var v = entry.{src.field_name};")
                w.line("out[i] = (v != null) ? v.toFloat() : null;")

    if info.array_nullable:
        with w.block("if (raw != null)"):
            fill()
    else:
        fill()
    w.line(f"{values} = out;")
    if element.min_auto:
        w.line(f"{graph_min_field(element.id)} = WfbSeries.autoMin(out);")
    if element.max_auto:
        w.line(f"{graph_max_field(element.id)} = WfbSeries.autoMax(out);")


def _fallback_fraction(element: Progress) -> str:
    """The `progress` fallback, as a Float in 0.0-1.0.

    Two things have to be true of it, and neither is automatic.  It must be a
    **Float**: `fraction` is reassigned from `_fraction()` (a Float) in the
    branch below, and a `var` first bound to a Number makes the whole thing a
    `PolyType<Float or Number>` that `WfbArc.drawProgress`'s `Float` parameter
    rejects under `-l 3`.  And it must be **in range**: the real path is
    clamped by `WfbMath.percent`, so an unclamped fallback is the one way a
    bar could be drawn wider than its own box.  A constant is checked at build
    time (wfb/ir.py) and emitted bare; anything else is clamped on device.
    """
    fallback = element.fallback
    if fallback.is_constant:
        return f"{float(fallback.constant)}f"
    return f"WfbMath.clamp({fallback.code}, 0.0, 1.0).toFloat()"


def _fraction(element: Progress) -> str:
    return f"WfbMath.percent({element.value.code}, {element.maximum.code}) / 100.0"


