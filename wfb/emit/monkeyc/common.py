@dataclass
class SourceFile:
    """One generated file, and where it belongs in the project."""

    #: Relative to the build directory, e.g. ``source/SliceView.mc``.
    path: str
    text: str


def source_label(path) -> str:
    """The design's path as it should appear in a generated header.

    Relative to the working directory when it is under it, and the bare filename
    otherwise.  An absolute path would make generated output differ between
    machines, which would defeat the golden-file tests and make every diff noisy.
    """
    try:
        relative = os.path.relpath(Path(path).resolve(), Path.cwd())
    except (OSError, ValueError):
        return Path(path).name
    return Path(path).name if relative.startswith("..") else relative


def header(face: Face, extra: str = "") -> str:
    lines = [
        f"Generated by garmin-wf-builder {__version__} -- do not edit.",
        f"Source:    {source_label(face.source_path)}",
        f"Face:      {face.name} (format {face.format})",
    ]
    if extra:
        lines.append(extra)
    lines.append("Regenerate with `wfb build`.  Edits here are lost on the next build;")
    lines.append("hand-written Monkey C belongs in a `raw` element instead (ADR 0007).")
    return "\n".join(lines)


@dataclass(frozen=True)
class McLiteral:
    """A layout constant whose value is not a plain number.

    Every other constant is a `Number` or a `Float` that `_mc_type`/`_mc_number`
    can derive from the Python value.  A polygon's point array is the one
    exception, so it carries its own declared Monkey C type and source text.

    **The type is not cosmetic and the shape was chosen by building, not by
    preference** (`docs/research/probes/polygon-const/`).  `Dc.fillPolygon`
    takes `Array<Graphics.Point2D>`, and `Point2D` is the *fixed-size* tuple
    type `[Numeric, Numeric]`: declaring the const `Array<Array<Number> >`
    instead compiles the const fine and then fails at the call site under
    `-l 3`.  A module-level `const` of the right type is accepted, so the array
    lives in `Layout` like every other coordinate (ADR 0004) rather than being
    assembled from per-coordinate constants at the call site.
    """

    type: str
    code: str


def hold_targets(face: Face) -> list:
    """Elements a hold does something with, in draw order.

    An `on_hold:` on any element.  Empty means a passive face, and the whole
    delegate is then omitted.
    """
    return [e for e in face.walk() if e.on_hold is not None]


def complication_slots(face: Face) -> list:
    """Every `complication_slot` element, in draw order.

    Drives the editor-only machinery (`AppBase.onStart`'s edit-mode flag,
    `WatchFaceDelegate.onTap`/`getComplicationDrawable`, the generated
    `SlotDrawable`) -- all of it gated on this being non-empty, never on
    `face.config_data` alone, since a declared `config: data:` slot with no
    `complication_slot` element drawing it would otherwise pull in a whole
    editor-highlight seam for nothing on screen to highlight.
    """
    return [e for e in face.walk() if isinstance(e, ComplicationSlot)]


def needs_delegate(face: Face) -> bool:
    """Does this design need a `WatchFaceDelegate` at all?

    Two independent reasons, either sufficient on its own: a hold target
    (`on_hold:`), or a declared `config:` block, whose
    `onWatchFaceConfigEdited` lives on the delegate the same way `onPress`
    does.  A design with `config:` and no interactivity still needs the
    delegate purely to re-read settings when the editor reports a change.
    """
    return bool(hold_targets(face)) or face.has_config


def _editor_slot_pairs(face: Face) -> list:
    """Every `complication_slot` element this design actually draws, paired
    with its declared slot's `<complication id=...>` unique id
    (`wfb.ir.config_data_ids`) -- one pair per distinct slot *name*, in
    document order.

    Backs every editor-only piece (`onTap`'s hit-test, `getComplicationDrawable`'s
    dispatch, the generated `SlotDrawable`): all three need "which element
    goes with which unique id", and deduplicating by slot name here, once, is
    what keeps two elements bound to the same slot -- legal, if unusual, and
    not otherwise checked anywhere in this project -- from generating two
    `case`/`if` labels for one id.
    """
    ids = config_data_ids(face)
    seen: set[str] = set()
    pairs = []
    for element in complication_slots(face):
        if element.slot in seen:
            continue
        seen.add(element.slot)
        unique = ids.get(element.slot)
        if unique is not None:
            pairs.append((element, unique))
    return pairs


