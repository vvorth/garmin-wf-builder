def _field(name: str) -> str:
    parts = [p for p in name.replace("-", "_").split("_") if p]
    return "font" + "".join(p[:1].upper() + p[1:] for p in parts)


def _aod_font_field(name: str) -> str:
    """The view field a baked font used *only* by an `aod: {font: ...}`
    override (never drawn while awake) is loaded into -- `_field(name)`
    with an `Aod` suffix, so it never collides with an awake field for a
    font of the same name used elsewhere too (plan 14 §4.3: "a resource
    font used only as an AOD override is a second resource").
    """
    return f"{_field(name)}Aod"


def _color(expression: Expression | None) -> str:
    if expression is None:
        return "Graphics.COLOR_WHITE"
    return expression.code


#: `aod: {dim: ...}` (plan 14 slice 3), as the `(num, den)` integer ratio
#: `wfb.palette.dim_channel`/the generated `WfbColor.dim` both read -- `None`
#: means "no dimming", the same as the face never writing `dim:` at all
#: (`Face.aod_dim`'s own normalisation folds `dim: 1` into this too).
AodDim = tuple[int, int] | None


def _dim_color_code(expression: Expression | None, awake_code: str, dim: "AodDim") -> str:
    """The AOD Monkey C expression for one colour that has **no** explicit
    `aod: {color: ...}`-style override, when the face's own `aod: {dim:
    ...}` still applies to it (plan 14 §4.5: dimming reaches every colour
    the AOD frame draws, override or not).

    A colour whose value is fixed at build time -- a bare hex literal, or a
    `palette.<name>` reference, `Expression.is_constant` either way -- is
    pre-dimmed into a second literal here, in Python, once, rather than
    spending a runtime call on arithmetic whose answer never changes
    (`wfb.palette.Color.dim`). Anything else -- `config.colors.<role>` (a
    view field the wearer's own on-device pick can repoint) or a
    conditional between several colours -- is dimmed on-device instead, with
    the exact same integer math (`WfbColor.dim`, `runtime-lib/WfbColor.mc`).
    `expression is None` is a `color:` an element never wrote at all, which
    defaults to `Graphics.COLOR_WHITE` (`_color`) and is dimmed like any
    other constant.
    """
    num, den = dim
    if expression is None or expression.is_constant:
        value = expression.constant if expression is not None else 0xFFFFFF
        return Color.parse(value).dim(num, den).as_monkeyc()
    return f"WfbColor.dim({awake_code}, {num}, {den})"


@dataclass(frozen=True)
class AodStyle:
    """How this build restyles a draw call for the AMOLED always-on frame
    (plan 14 §4.2): every override becomes an inline ``_aod ? <aod> :
    <awake>`` ternary at the draw call site.

    ``on`` is whether this build emits AOD code at all (some target is
    AMOLED, `wfb.availability.Guards.amoled_target`); ``dim`` is the
    face-wide `aod: {dim: ...}` ratio. Both are derived once, in
    `emit_view`, and every per-kind emitter takes this one object. With
    ``on`` false every method hands back the awake code unchanged, which is
    what keeps an all-MIP build byte-identical to a face with no `aod:`.
    """

    on: bool = False
    dim: AodDim = None

    def value(self, override: str | None, awake_code: str) -> str:
        """``(_aod ? <override> : <awake>)``, or ``awake_code`` alone when
        there is no override (already rendered as Monkey C: a `Layout`
        constant, a literal, a font expression, ...)."""
        if not self.on or override is None:
            return awake_code
        return f"(_aod ? {override} : {awake_code})"

    def layout(self, prefix: str, suffix: str, has_override: bool) -> str:
        """``Layout.<P>_<suffix>``, ternary against ``Layout.<P>_AOD_<suffix>``
        when the element's resolved `aod:` overrides that key -- the shape
        every `Layout`-backed override (`thickness:`, `bar_width:`) takes."""
        override = f"Layout.{prefix}_AOD_{suffix}" if has_override else None
        return self.value(override, f"Layout.{prefix}_{suffix}")

    def color(self, element, key: str, awake_code: str | None = None) -> str:
        """One colour argument (`color`/`track_color`/`icon_color`) of an
        element shown in AOD: its own `aod:` override for ``key`` if it has
        one, else its awake colour dimmed by `dim` (which reaches every
        colour the AOD frame draws), else the awake colour unchanged.
        ``awake_code`` defaults to the element's own ``key`` colour.

        An override colour is a fully resolved `Expression` built by the same
        machinery as the element's own `color:`, so it follows
        `color_scheme:`/`config.colors` at runtime exactly as the awake one
        does (plan 14 §4.6). Which of the three applies is `aod_color_choice`
        (`wfb.ir`), the one decision `wfb.preview._aod_color` also reads --
        this method only turns that decision into Monkey C.
        """
        expression = getattr(element, key, None)
        if awake_code is None:
            awake_code = _color(expression)
        if not self.on or element.aod is None:
            return awake_code
        choice, override = aod_color_choice(element.aod, key, self.dim is not None)
        return self._render(choice, override, expression, awake_code)

    def part_color(self, element, color_expr: Expression | None) -> str:
        """`color`'s rule for one `hands`/`pattern` part: the element-level
        `aod: {color: ...}` applies uniformly to every part (§5.1), and
        `dim` dims each part's own colour."""
        awake_code = _color(color_expr)
        if not self.on or element.aod is None:
            return awake_code
        choice, override = aod_color_choice(element.aod, "color", self.dim is not None)
        return self._render(choice, override, color_expr, awake_code)

    def _render(self, choice: str, override: Expression | None,
                expression: Expression | None, awake_code: str) -> str:
        """`aod_color_choice`'s decision, printed as Monkey C: the override's
        own compiled code, `WfbColor.dim`/a pre-dimmed literal
        (`_dim_color_code`), or `awake_code` unchanged -- each wrapped in
        `self.value`'s `_aod ? ... : ...` ternary."""
        if choice == "override":
            return self.value(override.code, awake_code)
        if choice == "dim":
            return self.value(_dim_color_code(expression, awake_code, self.dim), awake_code)
        return awake_code


#: No AOD code at all -- the default for every emitter's `aod` parameter.
NO_AOD = AodStyle()


def _mc_bool(value: bool) -> str:
    return "true" if value else "false"


def _mc_float(value: float) -> str:
    """A bare `Float` literal for inline use in the view, not a `Layout`
    constant (`_mc_number` handles those, with a trailing `f`).  A Python
    float's own `repr` always carries a decimal point, which is what makes
    a literal like `0.10471975511965977` unambiguously `Float` rather than
    `Number` to the Monkey C parser with no suffix needed at all.
    """
    text = repr(float(value))
    return text if "." in text or "e" in text else text + ".0"


def _loaded_fonts(resolved: ResolvedFace) -> list[str]:
    """Every **bitmap** font resource this view loads once in `onLayout`
    through `WatchUi.loadResource`, in first-appearance draw order: an
    author's baked text fonts (a `text` element's, a `complication_slot`'s,
    a pattern `shape: text` part's) and the synthetic per-size icon fonts
    (`wfb.icons.font_key`) alike.

    **A `face:` (vector) font is never in this list** (plan 11): it is not
    a resource at all, and `_vector_fonts_used` covers it instead.
    """
    out: list[str] = []
    for placed in resolved.items:
        out.extend(kinds.for_placed(placed).loaded_fonts(placed))
    return list(dict.fromkeys(out))


def _aod_only_fonts(resolved: ResolvedFace) -> list[str]:
    """Baked (non-vector) custom fonts named only by a `text` element's own
    `aod: {font: ...}` override, and never drawn while awake (`_loaded_
    fonts`) -- plan 14 §4.3's "a resource font used only as an AOD override
    is a second resource": loaded in `onEnterSleep`, only when `_aod`, and
    released (nulled) in `onExitSleep`, so it does not sit in memory the
    whole time the way an ordinarily-loaded font does.

    Excludes an override that names the *same* resource the element already
    draws with while awake (nothing to load a second time -- the awake
    field already covers it). A `face:` (vector) font override, a
    `complication_slot`'s own `font:` override and a pattern's own `font:`
    override are all rejected outright as friendly build errors
    (`Builder._build_aod_authored`, `docs/limitations.md` §2), so none of
    them can ever reach this function -- only `PlacedText` is consulted.
    """
    awake = set(_loaded_fonts(resolved))
    out: list[str] = []
    for placed in resolved.items:
        if not isinstance(placed, PlacedText):
            continue
        aod = placed.element.aod
        if aod is None or aod.font is None or not aod.font_is_custom:
            continue
        if aod.font == placed.font.reference or aod.font in awake or aod.font in out:
            continue
        spec = resolved.face.fonts.get(aod.font)
        if spec is None or spec.is_vector:
            continue
        out.append(aod.font)
    return out


def _vector_fonts_used(resolved: ResolvedFace) -> list[str]:
    """Every `face:` (vector) font name a `text` element, or a pattern's own
    `shape: text` part, draws with, in first-appearance draw order -- the
    vector counterpart of :func:`_loaded_fonts` (built through
    `Graphics.getVectorFont`, not `WatchUi.loadResource`, plan 11 §3).  A
    declared but undrawn font contributes nothing.  `wfb.availability.
    vector_fonts_used(face)` answers the same question off the IR, for the
    build-wide guard decision made before any device is resolved.
    """
    out: list[str] = []
    for placed in resolved.items:
        out.extend(kinds.for_placed(placed).vector_fonts(placed))
    return list(dict.fromkeys(out))


def _describe(placed) -> str:
    return kinds.for_placed(placed).describe(placed)


def _and_list(items) -> str:
    items = list(items)
    if len(items) <= 1:
        return "".join(items)
    return ", ".join(items[:-1]) + " and " + items[-1]


def _article(noun: str) -> str:
    return f"{'an' if noun[:1].lower() in 'aeiou' else 'a'} {noun}"


def _mc_type(value: float | str | bool | McLiteral) -> str:
    """A `Layout` constant's declared Monkey C type -- every constant
    (`layout_constants.Constants`) is typed and rendered through this and
    `_mc_number`.  `bool` is checked before `float`/`int`: Python's `bool`
    is a subtype of `int`, so the order matters or `True`/`False` would
    fall through to `Number`.
    """
    if isinstance(value, McLiteral):
        return value.type
    if isinstance(value, bool):
        return "Boolean"
    if isinstance(value, str):
        return "String"
    return "Float" if isinstance(value, float) else "Number"


def _mc_string(value: str) -> str:
    """A double-quoted Monkey C string literal for `value`.

    Every string this project ever emits into a `Layout` constant is a
    device-published face *name* (`Device.scalable_faces`, straight out of
    a device's own `simulator.json`) or the empty string (an unavailable
    font, plan 11 -- never drawn, since the null check at the call site
    always gates it) -- neither can contain a `"` or a control character in
    practice, but the two characters that would break the literal if they
    somehow did are still escaped rather than assumed absent.
    """
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _mc_number(value: float | str | bool | McLiteral) -> str:
    if isinstance(value, McLiteral):
        return value.code
    if isinstance(value, bool):
        return _mc_bool(value)
    if isinstance(value, str):
        return _mc_string(value)
    return f"{value}f" if isinstance(value, float) else str(int(value))
